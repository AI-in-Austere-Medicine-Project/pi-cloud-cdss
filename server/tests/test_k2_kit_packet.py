"""K2: the kit packet (owner, 2026-10-28).

"Kit packet: one page per drug in the bank with a signed dose, listing the
concentrations the kit file or SMOG shows, a SIGN line per concentration, and
a "two strengths stocked" option. Word and PDF under docs/authoring. Sign
nothing."

The packet is generated by tools/gen_kit_packet.py from the kit file and
KIT_PACKET_SMOG_STRENGTHS (the strengths SMOG CY24 shows, verbatim, with the
printed page). These tests pin the strengths file and the packet's pages. The
quote test needs the SMOG PDF and pdftotext; without them it skips.

    cd server && ./run_unit_tests.sh
"""
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys

import pytest

SERVER = pathlib.Path(__file__).resolve().parents[1]
ROOT = SERVER.parent
DOCS = ROOT / "docs" / "authoring"
SMOG_FILE = DOCS / "KIT_PACKET_SMOG_STRENGTHS_2026-10-28.json"
DOCX = DOCS / "KIT_PACKET_2026-10-28.docx"
PDF = DOCS / "KIT_PACKET_2026-10-28.pdf"
SMOG_PDF = pathlib.Path(os.environ.get(
    "SMOG_PDF", SERVER / "data/jts_protocols/SMOG_CY24_REVISION_FINAL.pdf"))

import drug_contracts  # noqa: E402


def _signed_drugs():
    served = drug_contracts.servable_entries()
    return [d for d in drug_contracts.DRUGS if served.get(d)]


def _smog():
    return json.loads(SMOG_FILE.read_text())["drugs"]


def test_the_packet_files_exist():
    for p in (SMOG_FILE, DOCX, PDF):
        assert p.is_file() and p.stat().st_size > 0, p


def test_smog_strengths_are_for_bank_drugs_with_a_signed_dose():
    assert set(_smog()) <= set(_signed_drugs())


def test_every_smog_strength_is_a_vial_or_an_infusion_with_a_page_and_a_quote():
    for drug, rows in _smog().items():
        for r in rows:
            assert r["kind"] in ("vial", "infusion"), (drug, r)
            assert r["mg_ml"] > 0 and isinstance(r["page"], int) and r["quote"].strip(), (drug, r)


@pytest.mark.skipif(not (SMOG_PDF.is_file() and shutil.which("pdftotext")),
                    reason="needs the SMOG PDF (SMOG_PDF) and pdftotext")
def test_every_smog_quote_is_on_its_printed_page():
    sys.path.insert(0, str(ROOT / "tools"))
    import gen_kit_packet as g
    g.SMOG_PDF = SMOG_PDF
    pages = g.smog_pages()
    missing = [(d, r["page"], r["quote"]) for d, rows in _smog().items() for r in rows
               if not g.quote_found(pages, r["page"], r["quote"])]
    assert missing == []


@pytest.mark.skipif(shutil.which("pdftotext") is None, reason="needs pdftotext")
def test_one_page_per_signed_drug_each_with_sign_lines_and_the_two_strengths_option():
    text = subprocess.run(["pdftotext", "-layout", str(PDF), "-"],
                          capture_output=True, text=True, check=True).stdout
    pages = text.split("\f")
    drugs = _signed_drugs()
    body = [p for p in pages[1:] if p.strip()]
    assert len(body) == len(drugs), "one page per bank drug with a signed dose, after the cover"
    for drug, page in zip(drugs, body):
        assert drug in page, drug
        assert page.count("SIGN as stocked") >= 1, drug
        assert "Two strengths stocked" in page and "One strength stocked" in page, drug
    # Nothing signed in the packet: every Signed line is blank.
    assert not re.search(r"Signed (?!doses)[A-Za-z]", text)
